#include <iostream>
using namespace std;

int main()
{
    int a,b;
    cout << "So nguyen a la: ";
    cin >> a;
    cout << "So nguyen b la: ";
    cin >> b;
    cout << "a+b= " << a + b << endl;
    cout << "a-b= " << a - b << endl;
    cout << "a*b= " << a * b << endl;
    cout << "a/b= " << a / b << endl;
    cout << "a%b= " << a % b << endl;
    return 0;
}